require("nvim-surround").setup({
	surrounds = {
		["*"] = {
			add = { "**", "**" },
			find = "%*%*.-%*%*",
			delete = "^(%*%*)().-(%*%*)()$",
		},
		["l"] = {
			add = { "[[", "]]" },
			find = "%[%[.-%]%]",
			delete = "^(%[%[)().-(%]%])()$",
		},
		["_"] = {
			add = { "_", "_" },
			find = "_.-_",
			delete = "^(_)().-(_)()$",
		},
		["c"] = {
			add = { { "```", "" }, { "", "```" } },
		},
	},
})
